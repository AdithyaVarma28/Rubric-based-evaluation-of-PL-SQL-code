
CREATE TABLE ACCOUNTS (
    ac_no NUMBER NOT NULL, br_no NUMBER NOT NULL, cust_no NUMBER NOT NULL, ac_type VARCHAR2(10) NOT NULL, bal NUMBER NOT NULL, PRIMARY KEY (ac_no)
);


CREATE TABLE BRANCHES (
    br_no NUMBER NOT NULL, br_name VARCHAR2(50) NOT NULL, loc VARCHAR2(50) NOT NULL, PRIMARY KEY (br_no)
);


CREATE TABLE CUSTOMER (
    cno NUMBER NOT NULL, cname VARCHAR2(100) NOT NULL, c_type VARCHAR2(10), PRIMARY KEY (cno)
);
